"""
RAG Agent
=========

Responsibility:
- Input:
    1. products.json generated by DataAgent
    2. KnowledgeBase folder containing historical cases, constraints, reports, templates

- Process:
    1. Load knowledge documents
    2. Split documents into chunks
    3. Convert chunks into local sentence-transformers embeddings
    4. Store embeddings into Chroma vector database
    5. Build a query from current products.json
    6. Retrieve relevant knowledge

- Output:
    retrieved_context.json

Performance design:
- Embedding model, Chroma vector store, and text splitter are cached
  within the current Python process.
- The first batch loads model resources.
- Later batches reuse the same resources instead of reloading weights.

This agent does NOT:
- clean Excel
- optimise loading
- validate constraints
- generate visualisation
- call a real LLM
"""

from __future__ import annotations

import argparse
import hashlib
import json
import time
from collections import Counter
from pathlib import Path
from threading import RLock
from typing import Any, ClassVar, Dict, List, Optional, Tuple

from langchain_chroma import Chroma
from langchain_core.documents import Document
from langchain_huggingface import HuggingFaceEmbeddings
from langchain_text_splitters import RecursiveCharacterTextSplitter


class RAGAgent:
    """
    RAGAgent uses LangChain + Chroma + local sentence-transformers embeddings.

    Expensive shared resources are cached at class level so that multiple
    batch-level RAGAgent instances created in one Python process do not
    repeatedly reload the same embedding model.
    """

    SUPPORTED_EXTENSIONS = {".txt", ".md", ".json"}

    _RESOURCE_CACHE: ClassVar[
        Dict[
            Tuple[str, str, str, str, int, int],
            Tuple[
                HuggingFaceEmbeddings,
                Chroma,
                RecursiveCharacterTextSplitter,
            ],
        ]
    ] = {}

    _RESOURCE_CACHE_LOCK = RLock()

    def __init__(
        self,
        products_json_path: str | Path = "Agents/products.json",
        knowledge_base_dir: str | Path = "KnowledgeBase",
        persist_directory: str | Path = "VectorDB/chroma_db",
        collection_name: str = "baosteel_loading_rag",
        embedding_model_name: str = (
            "sentence-transformers/paraphrase-multilingual-MiniLM-L12-v2"
        ),
        device: str = "cpu",
        chunk_size: int = 800,
        chunk_overlap: int = 120,
        cache_resources: bool = True,
    ) -> None:
        self.products_json_path = Path(products_json_path)
        self.knowledge_base_dir = Path(knowledge_base_dir)
        self.persist_directory = Path(persist_directory)
        self.collection_name = collection_name
        self.embedding_model_name = embedding_model_name
        self.device = device
        self.chunk_size = chunk_size
        self.chunk_overlap = chunk_overlap
        self.cache_resources = cache_resources

        self._resource_cache_key = self._build_resource_cache_key()

        (
            self.embeddings,
            self.vector_store,
            self.text_splitter,
            cache_hit,
        ) = self._get_or_create_resources()

        if cache_hit:
            print(
                "[RAGAgent] Reusing cached embedding model and "
                "Chroma vector store."
            )
        else:
            print(
                "[RAGAgent] Initialised embedding model and "
                "Chroma vector store."
            )

    # ============================================================
    # Shared resource cache
    # ============================================================

    def _build_resource_cache_key(
        self,
    ) -> Tuple[str, str, str, str, int, int]:
        """
        Resources can only be reused when their configuration is identical.
        """

        return (
            str(self.persist_directory.resolve()),
            self.collection_name,
            self.embedding_model_name,
            self.device,
            self.chunk_size,
            self.chunk_overlap,
        )

    def _get_or_create_resources(
        self,
    ) -> Tuple[
        HuggingFaceEmbeddings,
        Chroma,
        RecursiveCharacterTextSplitter,
        bool,
    ]:
        """
        Return cached expensive resources where possible.

        cache_hit=True means this RAGAgent did not reload model weights.
        """

        if not self.cache_resources:
            embeddings, vector_store, text_splitter = self._create_resources()

            return embeddings, vector_store, text_splitter, False

        with self._RESOURCE_CACHE_LOCK:
            cached_resources = self._RESOURCE_CACHE.get(
                self._resource_cache_key
            )

            if cached_resources is not None:
                embeddings, vector_store, text_splitter = cached_resources

                return embeddings, vector_store, text_splitter, True

            embeddings, vector_store, text_splitter = self._create_resources()

            self._RESOURCE_CACHE[self._resource_cache_key] = (
                embeddings,
                vector_store,
                text_splitter,
            )

            return embeddings, vector_store, text_splitter, False

    def _create_resources(
        self,
    ) -> Tuple[
        HuggingFaceEmbeddings,
        Chroma,
        RecursiveCharacterTextSplitter,
    ]:
        """
        Create expensive embedding and vector-store resources once.
        """

        self.persist_directory.mkdir(parents=True, exist_ok=True)

        embeddings = HuggingFaceEmbeddings(
            model_name=self.embedding_model_name,
            model_kwargs={"device": self.device},
            encode_kwargs={"normalize_embeddings": True},
        )

        vector_store = Chroma(
            collection_name=self.collection_name,
            embedding_function=embeddings,
            persist_directory=str(self.persist_directory),
        )

        text_splitter = RecursiveCharacterTextSplitter(
            chunk_size=self.chunk_size,
            chunk_overlap=self.chunk_overlap,
            separators=[
                "\n\n",
                "\n",
                "。",
                ".",
                "；",
                ";",
                "，",
                ",",
                " ",
                "",
            ],
        )

        return embeddings, vector_store, text_splitter

    def _update_cached_vector_store(self) -> None:
        """
        Update cache after rebuild_vector_db() creates a new collection.
        """

        if not self.cache_resources:
            return

        with self._RESOURCE_CACHE_LOCK:
            self._RESOURCE_CACHE[self._resource_cache_key] = (
                self.embeddings,
                self.vector_store,
                self.text_splitter,
            )

    @classmethod
    def clear_resource_cache(cls) -> None:
        """
        Clear only in-memory resources.

        This does not delete the persisted Chroma vector database.
        """

        with cls._RESOURCE_CACHE_LOCK:
            cls._RESOURCE_CACHE.clear()

        print("[RAGAgent] In-memory resource cache cleared.")

    # ============================================================
    # Public pipeline
    # ============================================================

    def run(
        self,
        output_path: str | Path = "Agents/retrieved_context.json",
        rebuild_vector_db: bool = False,
        top_k: int = 6,
    ) -> Dict[str, Any]:
        """
        Main RAGAgent pipeline.

        products.json + KnowledgeBase -> Chroma retrieval
        -> retrieved_context.json
        """

        pipeline_started = time.perf_counter()

        vector_db_started = time.perf_counter()

        if rebuild_vector_db:
            self.rebuild_vector_db()
        elif self._vector_db_is_empty():
            self.build_vector_db()

        vector_db_seconds = time.perf_counter() - vector_db_started

        product_started = time.perf_counter()

        products = self.load_products()
        query_summary = self.summarise_products(products)
        query_text = self.build_query_text(query_summary)

        product_summary_seconds = time.perf_counter() - product_started

        retrieval_started = time.perf_counter()

        retrieved_documents = self.retrieve(
            query_text=query_text,
            top_k=top_k,
        )

        retrieval_seconds = time.perf_counter() - retrieval_started

        result = {
            "query_summary": query_summary,
            "query_text": query_text,
            "retrieved_documents": retrieved_documents,
            "recommended_context": self.build_recommended_context(
                retrieved_documents
            ),
            "timing_seconds": {
                "vector_db_prepare": round(vector_db_seconds, 4),
                "product_summary": round(product_summary_seconds, 4),
                "retrieval": round(retrieval_seconds, 4),
                "total": round(
                    time.perf_counter() - pipeline_started,
                    4,
                ),
            },
        }

        export_started = time.perf_counter()

        self.export_json(result, output_path)

        export_seconds = time.perf_counter() - export_started
        total_seconds = time.perf_counter() - pipeline_started

        result["timing_seconds"]["export"] = round(export_seconds, 4)
        result["timing_seconds"]["total"] = round(total_seconds, 4)

        # Export again to include final export timing in the saved JSON.
        self.export_json(result, output_path)

        print(
            f"[RAGAgent] Retrieved {len(retrieved_documents)} "
            "document chunks."
        )
        print(f"[RAGAgent] Output saved to: {output_path}")
        print(
            "[RAGAgent] Timing | "
            f"vector_db={vector_db_seconds:.2f}s | "
            f"product_summary={product_summary_seconds:.2f}s | "
            f"retrieval={retrieval_seconds:.2f}s | "
            f"export={export_seconds:.2f}s | "
            f"total={total_seconds:.2f}s"
        )

        return result

    # ============================================================
    # Product JSON handling
    # ============================================================

    def load_products(self) -> List[Dict[str, Any]]:
        """Load products.json generated by DataAgent."""

        if not self.products_json_path.exists():
            raise FileNotFoundError(
                f"products.json not found: {self.products_json_path}. "
                "Please run DataAgent first."
            )

        with self.products_json_path.open("r", encoding="utf-8") as f:
            data = json.load(f)

        if not isinstance(data, list):
            raise ValueError(
                "products.json should contain a list of product records."
            )

        return data

    def summarise_products(
        self,
        products: List[Dict[str, Any]],
    ) -> Dict[str, Any]:
        """Create a structured summary of current product data."""

        destinations = [
            str(product.get("destination", "")).strip()
            for product in products
        ]
        destinations = [
            destination
            for destination in destinations
            if destination
        ]

        weights = [
            self._product_weight_kg(product)
            for product in products
        ]

        widths = [
            self._safe_float(product.get("width", 0))
            for product in products
        ]

        outer_diameters = [
            self._safe_float(
                product.get(
                    "outer_diameter",
                    product.get("length", 0),
                )
            )
            for product in products
        ]

        total_weight_kg = sum(weights)

        return {
            "num_products": len(products),
            "destinations": sorted(list(set(destinations))),
            "destination_counts": dict(Counter(destinations)),
            "total_weight_kg": total_weight_kg,
            "average_weight_kg": (
                total_weight_kg / len(products)
                if products
                else 0
            ),
            "max_weight_kg": max(weights) if weights else 0,
            "min_weight_kg": min(weights) if weights else 0,
            "average_width": (
                sum(widths) / len(widths)
                if widths
                else 0
            ),
            "average_outer_diameter": (
                sum(outer_diameters) / len(outer_diameters)
                if outer_diameters
                else 0
            ),
            "has_multiple_destinations": len(set(destinations)) > 1,
        }

    def build_query_text(
        self,
        query_summary: Dict[str, Any],
    ) -> str:
        """
        Build semantic retrieval query from current order/product summary.
        """

        destinations = ", ".join(
            query_summary.get("destinations", [])
        )

        query = f"""
Current steel coil loading task summary:

Number of products: {query_summary.get("num_products")}
Destinations: {destinations}
Destination distribution: {query_summary.get("destination_counts")}
Total weight in kg: {query_summary.get("total_weight_kg")}
Average product weight in kg: {query_summary.get("average_weight_kg")}
Maximum product weight in kg: {query_summary.get("max_weight_kg")}
Average width: {query_summary.get("average_width")}
Average outer diameter: {query_summary.get("average_outer_diameter")}
Multiple destinations: {query_summary.get("has_multiple_destinations")}

Retrieve relevant knowledge about:
- steel coil loading optimisation
- wagon loading constraints
- destination grouping
- axle weight balance
- centerline balance
- diagonal balance
- boundary checking
- overlap checking
- historical successful loading cases
- historical failed loading cases
- report explanation template
- strategy selection for greedy, simulated annealing, or rule-based loading
""".strip()

        return query

    # ============================================================
    # KnowledgeBase loading and vector DB building
    # ============================================================

    def build_vector_db(self) -> None:
        """
        Build Chroma vector database from KnowledgeBase documents.

        If the vector DB already contains documents, this adds documents.
        Use rebuild_vector_db() to clear then rebuild.
        """

        documents = self.load_knowledge_documents()

        if not documents:
            raise FileNotFoundError(
                f"No knowledge documents found in "
                f"{self.knowledge_base_dir}. "
                "Please add .md, .txt, or .json files, or run with "
                "--init-kb to create examples."
            )

        chunks = self.text_splitter.split_documents(documents)
        ids = [
            self._document_id(chunk, index)
            for index, chunk in enumerate(chunks)
        ]

        self.vector_store.add_documents(
            documents=chunks,
            ids=ids,
        )

        print(f"[RAGAgent] Loaded {len(documents)} source documents.")
        print(
            f"[RAGAgent] Added {len(chunks)} chunks to "
            "Chroma vector DB."
        )
        print(f"[RAGAgent] Vector DB path: {self.persist_directory}")

    def rebuild_vector_db(self) -> None:
        """
        Rebuild Chroma vector database from KnowledgeBase.

        On Windows, delete the collection rather than the entire folder,
        because chroma.sqlite3 may be locked by the current Python process.
        """

        self.persist_directory.mkdir(parents=True, exist_ok=True)

        try:
            self.vector_store.delete_collection()
            print(
                f"[RAGAgent] Deleted old Chroma collection: "
                f"{self.collection_name}"
            )
        except Exception as exc:
            print(
                "[RAGAgent] No existing collection deleted, "
                f"reason: {exc}"
            )

        self.vector_store = Chroma(
            collection_name=self.collection_name,
            embedding_function=self.embeddings,
            persist_directory=str(self.persist_directory),
        )

        self._update_cached_vector_store()
        self.build_vector_db()

    def load_knowledge_documents(self) -> List[Document]:
        """
        Load all supported documents from KnowledgeBase.

        Supported:
        - .md
        - .txt
        - .json
        """

        if not self.knowledge_base_dir.exists():
            return []

        documents: List[Document] = []

        for file_path in self.knowledge_base_dir.rglob("*"):
            if not file_path.is_file():
                continue

            if file_path.suffix.lower() not in self.SUPPORTED_EXTENSIONS:
                continue

            document = self._load_single_knowledge_file(file_path)

            if document is not None:
                documents.append(document)

        return documents

    def _load_single_knowledge_file(
        self,
        file_path: Path,
    ) -> Optional[Document]:
        """Load one knowledge document and attach useful metadata."""

        try:
            if file_path.suffix.lower() == ".json":
                with file_path.open("r", encoding="utf-8") as f:
                    data = json.load(f)

                content = json.dumps(
                    data,
                    ensure_ascii=False,
                    indent=2,
                )
            else:
                content = file_path.read_text(encoding="utf-8")

        except UnicodeDecodeError:
            content = file_path.read_text(
                encoding="utf-8",
                errors="ignore",
            )

        except Exception as exc:
            print(
                f"[RAGAgent] Skipped file {file_path}. "
                f"Reason: {exc}"
            )
            return None

        content = content.strip()

        if not content:
            return None

        relative_source = str(
            file_path.relative_to(self.knowledge_base_dir)
        ).replace("\\", "/")

        metadata = {
            "source": relative_source,
            "file_name": file_path.name,
            "doc_type": self._infer_doc_type(file_path),
        }

        return Document(
            page_content=content,
            metadata=metadata,
        )

    def _infer_doc_type(self, file_path: Path) -> str:
        """Infer document type from folder name or file name."""

        parts = [part.lower() for part in file_path.parts]
        name = file_path.name.lower()

        if "constraint" in name or "constraints" in parts:
            return "constraint"

        if "historical" in parts or "case" in name:
            return "historical_case"

        if "failed" in name or "failure" in name:
            return "failed_case"

        if "template" in name or "report_templates" in parts:
            return "report_template"

        return "general_knowledge"

    # ============================================================
    # Retrieval
    # ============================================================

    def retrieve(
        self,
        query_text: str,
        top_k: int = 6,
    ) -> List[Dict[str, Any]]:
        """
        Retrieve relevant chunks from Chroma.

        Chroma returns lower distance for more similar documents.
        """

        results: List[Tuple[Document, float]] = (
            self.vector_store.similarity_search_with_score(
                query=query_text,
                k=top_k,
            )
        )

        retrieved_documents: List[Dict[str, Any]] = []

        for rank, (document, score) in enumerate(results, start=1):
            retrieved_documents.append(
                {
                    "rank": rank,
                    "score": float(score),
                    "source": document.metadata.get("source"),
                    "doc_type": document.metadata.get("doc_type"),
                    "file_name": document.metadata.get("file_name"),
                    "content": document.page_content,
                }
            )

        return retrieved_documents

    def build_recommended_context(
        self,
        retrieved_documents: List[Dict[str, Any]],
    ) -> str:
        """
        Build compact context string for the LLM Agent.
        """

        if not retrieved_documents:
            return "No relevant RAG context was retrieved."

        sections = []

        for document in retrieved_documents:
            section = f"""
[Rank {document["rank"]}] Source: {document.get("source")}
Document type: {document.get("doc_type")}
Retrieval score: {document.get("score")}

Content:
{document.get("content")}
""".strip()

            sections.append(section)

        return "\n\n---\n\n".join(sections)

    # ============================================================
    # Example KnowledgeBase
    # ============================================================

    def create_example_knowledge_base(self) -> None:
        """
        Create an example KnowledgeBase for initial testing.
        """

        constraints_dir = self.knowledge_base_dir / "constraints"
        cases_dir = self.knowledge_base_dir / "historical_cases"
        templates_dir = self.knowledge_base_dir / "report_templates"

        constraints_dir.mkdir(parents=True, exist_ok=True)
        cases_dir.mkdir(parents=True, exist_ok=True)
        templates_dir.mkdir(parents=True, exist_ok=True)

        (constraints_dir / "loading_constraints.md").write_text(
            """
# Steel Coil Loading Constraints

The loading solution must satisfy several operational constraints.

1. Weight limit:
Each wagon has a maximum loading capacity. The total gross weight of all products assigned to one wagon must not exceed the wagon limit.

2. Boundary constraint:
Every product must be placed inside the wagon loading area. No product can exceed the wagon length or width.

3. Overlap constraint:
Two products cannot occupy the same physical space.

4. Centerline balance:
The weight distribution on the left and right sides of the wagon centerline should be balanced. Heavy coils should not all be placed on the same side.

5. Axle weight balance:
The front and rear parts of the wagon should have a reasonable weight distribution. Heavy products should be distributed along the wagon length.

6. Diagonal balance:
The two diagonal regions of the wagon should not have extreme weight imbalance.
""".strip(),
            encoding="utf-8",
        )

        (constraints_dir / "centerline_balance.md").write_text(
            """
# Centerline Balance

Centerline balance is used to evaluate whether the left and right sides of the wagon are balanced.

For steel coil loading, heavy products should be placed close to the central width line where possible.
If many heavy coils are placed only on one side, the solution may be unsafe even if the total wagon weight is acceptable.

A balance-aware loading strategy should:
- place heavy products near the centerline;
- distribute product weights between the left and right sides;
- check the final left-right weight difference after placement.
""".strip(),
            encoding="utf-8",
        )

        (cases_dir / "case_001_successful_multi_destination_loading.md").write_text(
            """
# Historical Case 001: Successful Multi-Destination Loading

This case involved steel coils for multiple destinations.
The successful strategy was to first group products by destination and then apply weight-aware greedy placement.

Important observations:
- Destination grouping improved unloading clarity.
- Strict destination grouping alone was not enough.
- Heavy coils were placed closer to the centerline.
- After greedy placement, balance checks were applied.
- The final solution reduced the number of wagons while satisfying boundary and overlap constraints.

Recommended strategy:
Use destination grouping first, then apply balance-aware greedy placement.
""".strip(),
            encoding="utf-8",
        )

        (cases_dir / "failed_case_001_left_right_imbalance.md").write_text(
            """
# Failed Case 001: Left-Right Imbalance

This failed case placed most heavy products on one side of the wagon.
Although the total weight did not exceed the wagon capacity, the centerline balance failed.

Failure reason:
- Too many heavy coils were assigned to the same side.
- The algorithm prioritised compact placement but ignored left-right weight balance.
- The visualisation showed obvious asymmetry.

Lesson:
For heavy steel coils, compact placement should not be the only objective.
The optimisation agent must include balance-aware scoring or a post-placement validation step.
""".strip(),
            encoding="utf-8",
        )

        (cases_dir / "case_002_greedy_plus_sa.md").write_text(
            """
# Historical Case 002: Greedy Plus Simulated Annealing

In this case, the greedy algorithm generated a quick initial loading solution.
However, the initial solution had several balance issues.

A simulated annealing improvement step was then applied.
The improvement process swapped product positions and adjusted orientations to reduce balance violations.

Outcome:
- The number of wagons remained the same.
- Centerline balance improved.
- Diagonal balance improved.
- The final visualisation was easier for operators to verify.

Recommended strategy:
Use greedy placement for the initial solution and simulated annealing for improvement.
""".strip(),
            encoding="utf-8",
        )

        (templates_dir / "loading_report_template.md").write_text(
            """
# Loading Report Template

A loading report should include:

1. Input summary
- Number of products
- Total weight
- Destinations
- Product size distribution

2. Strategy explanation
- Why the current loading strategy was selected
- Whether historical cases were retrieved by RAG
- Which constraints were prioritised

3. Optimisation result
- Number of wagons
- Products assigned to each wagon
- Loading utilisation

4. Validation result
- Weight limit
- Boundary check
- Overlap check
- Centerline balance
- Axle balance
- Diagonal balance

5. Visualisation explanation
- Explain product placement
- Highlight heavy product locations
- Explain whether the layout is operationally acceptable
""".strip(),
            encoding="utf-8",
        )

        print(
            f"[RAGAgent] Example KnowledgeBase created at: "
            f"{self.knowledge_base_dir}"
        )

    # ============================================================
    # Utilities
    # ============================================================

    def export_json(
        self,
        result: Dict[str, Any],
        output_path: str | Path,
    ) -> Path:
        """Export retrieved context to JSON."""

        output_path = Path(output_path)
        output_path.parent.mkdir(parents=True, exist_ok=True)

        with output_path.open("w", encoding="utf-8") as f:
            json.dump(result, f, ensure_ascii=False, indent=2)

        return output_path

    def _vector_db_is_empty(self) -> bool:
        """Check whether the current Chroma collection is empty."""

        try:
            return self.vector_store._collection.count() == 0
        except Exception:
            return True

    def _document_id(
        self,
        document: Document,
        index: int,
    ) -> str:
        """Generate stable ID for each chunk."""

        raw = (
            str(document.metadata.get("source", "unknown"))
            + "|"
            + str(index)
            + "|"
            + document.page_content[:200]
        )

        return hashlib.md5(raw.encode("utf-8")).hexdigest()

    @staticmethod
    def _safe_float(value: Any) -> float:
        try:
            if value is None:
                return 0.0

            return float(value)

        except Exception:
            return 0.0

    @classmethod
    def _product_weight_kg(cls, product: Dict[str, Any]) -> float:
        """Return a canonical product weight in kilograms."""

        for field in ("gross_weight_kg", "weight"):
            value = product.get(field)
            if value not in (None, ""):
                return cls._safe_float(value)

        return cls._safe_float(product.get("gross_weight_tonne")) * 1000.0


def main() -> None:
    parser = argparse.ArgumentParser(
        description=(
            "RAG Agent using LangChain + Chroma + "
            "sentence-transformers."
        )
    )

    parser.add_argument(
        "--products",
        default="Agents/products.json",
        help="Path to products.json generated by DataAgent.",
    )
    parser.add_argument(
        "--kb",
        default="KnowledgeBase",
        help="Path to KnowledgeBase folder.",
    )
    parser.add_argument(
        "--db",
        default="VectorDB/chroma_db",
        help="Path to Chroma persistent database folder.",
    )
    parser.add_argument(
        "--output",
        default="Agents/retrieved_context.json",
        help="Path to output retrieved_context.json.",
    )
    parser.add_argument(
        "--collection",
        default="baosteel_loading_rag",
        help="Chroma collection name.",
    )
    parser.add_argument(
        "--model",
        default=(
            "sentence-transformers/"
            "paraphrase-multilingual-MiniLM-L12-v2"
        ),
        help="Local sentence-transformers embedding model name.",
    )
    parser.add_argument(
        "--device",
        default="cpu",
        choices=["cpu", "cuda"],
        help="Embedding device. Use cuda only if PyTorch supports GPU.",
    )
    parser.add_argument(
        "--top-k",
        type=int,
        default=6,
        help="Number of retrieved chunks.",
    )
    parser.add_argument(
        "--rebuild",
        action="store_true",
        help="Delete old Chroma DB collection and rebuild.",
    )
    parser.add_argument(
        "--init-kb",
        action="store_true",
        help="Create example KnowledgeBase files for testing.",
    )

    args = parser.parse_args()

    agent = RAGAgent(
        products_json_path=args.products,
        knowledge_base_dir=args.kb,
        persist_directory=args.db,
        collection_name=args.collection,
        embedding_model_name=args.model,
        device=args.device,
    )

    if args.init_kb:
        agent.create_example_knowledge_base()
        print(
            "[RAGAgent] Example KB created. "
            "You can now run with --rebuild."
        )
        return

    agent.run(
        output_path=args.output,
        rebuild_vector_db=args.rebuild,
        top_k=args.top_k,
    )


if __name__ == "__main__":
    main()
