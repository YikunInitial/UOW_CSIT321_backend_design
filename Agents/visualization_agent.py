"""
Visualization Agent
===================

Responsibility:
- Input:
    1. Agents/loading_solution.json

- Process:
    1. Read loading solution generated by OptimisationAgent
    2. Draw 2D loading layout for each wagon
    3. Mark wagon boundary, centerline, and front/rear line
    4. Mark each product's position, size, destination, and weight
    5. Generate PNG images
    6. Generate a PDF visualisation report
    7. Export visualization_summary.json

- Output:
    1. demo_outputs/W001_layout.png
    2. demo_outputs/W002_layout.png
    3. demo_outputs/loading_visualisation_report.pdf
    4. Agents/visualization_summary.json

This agent does NOT:
- optimise loading
- validate constraints
- call LLM
- modify loading coordinates

Install:
    pip install matplotlib

Run:
    python Agents/visualization_agent.py

Optional:
    python Agents/visualization_agent.py --solution Agents/loading_solution.json --output-dir demo_outputs
"""

from __future__ import annotations

import argparse
import json
import math
from pathlib import Path
from typing import Any, Dict, List, Optional

import matplotlib.pyplot as plt
from matplotlib.backends.backend_pdf import PdfPages
from matplotlib.patches import Rectangle

import matplotlib

matplotlib.rcParams["font.sans-serif"] = [
    "Microsoft YaHei",
    "SimHei",
    "Arial Unicode MS",
    "DejaVu Sans",
]
matplotlib.rcParams["axes.unicode_minus"] = False


class VisualizationAgent:
    """
    VisualizationAgent converts loading_solution.json into visual layouts.

    Input:
        Agents/loading_solution.json

    Outputs:
        demo_outputs/*.png
        demo_outputs/loading_visualisation_report.pdf
        Agents/visualization_summary.json
    """

    def __init__(
        self,
        loading_solution_path: str | Path = "Agents/loading_solution.json",
        output_dir: str | Path = "demo_outputs",
        summary_output_path: str | Path = "Agents/visualization_summary.json",
        figure_dpi: int = 200,
    ) -> None:
        self.loading_solution_path = Path(loading_solution_path)
        self.output_dir = Path(output_dir)
        self.summary_output_path = Path(summary_output_path)
        self.figure_dpi = figure_dpi

        self.output_dir.mkdir(parents=True, exist_ok=True)
        self.summary_output_path.parent.mkdir(parents=True, exist_ok=True)

    # ============================================================
    # Main pipeline
    # ============================================================

    def run(self) -> Dict[str, Any]:
        loading_solution = self.load_loading_solution()
        wagons = loading_solution.get("wagons", [])

        if not wagons:
            raise ValueError("No wagons found in loading_solution.json.")

        layout_image_paths: List[str] = []

        for wagon in wagons:
            image_path = self.output_dir / f"{wagon.get('wagon_id', 'wagon')}_layout.png"
            self.draw_wagon_layout(
                wagon=wagon,
                output_path=image_path,
                title_suffix="Final Loading Layout",
            )
            layout_image_paths.append(str(image_path))

        pdf_path = self.output_dir / "loading_visualisation_report.pdf"
        self.generate_pdf_report(
            loading_solution=loading_solution,
            wagons=wagons,
            pdf_path=pdf_path,
        )

        summary = self.build_visualization_summary(
            loading_solution=loading_solution,
            layout_image_paths=layout_image_paths,
            pdf_path=str(pdf_path),
        )

        self.export_json(summary, self.summary_output_path)

        self._safe_log(
            f"[VisualizationAgent] Generated {len(layout_image_paths)} "
            "layout image(s)."
        )
        self._safe_log(f"[VisualizationAgent] PDF report saved to: {pdf_path}")
        self._safe_log(
            f"[VisualizationAgent] Summary saved to: "
            f"{self.summary_output_path}"
        )

        return summary

    @staticmethod
    def _safe_log(message: str) -> None:
        try:
            print(message)
        except (OSError, UnicodeEncodeError):
            pass

    # ============================================================
    # Input
    # ============================================================

    def load_loading_solution(self) -> Dict[str, Any]:
        if not self.loading_solution_path.exists():
            raise FileNotFoundError(
                f"loading_solution.json not found: {self.loading_solution_path}. "
                "Please run OptimisationAgent first."
            )

        with self.loading_solution_path.open("r", encoding="utf-8") as f:
            data = json.load(f)

        if not isinstance(data, dict):
            raise ValueError("loading_solution.json should contain a JSON object.")

        return data

    # ============================================================
    # Drawing
    # ============================================================

    def draw_wagon_layout(
        self,
        wagon: Dict[str, Any],
        output_path: str | Path,
        title_suffix: str = "Loading Layout",
    ) -> None:
        wagon_id = wagon.get("wagon_id", "Unknown Wagon")
        wagon_length = self.safe_float(wagon.get("length", 12000))
        wagon_width = self.safe_float(wagon.get("width", 2500))
        products = wagon.get("products", [])

        fig_width = 13
        fig_height = max(4, fig_width * wagon_width / wagon_length)

        fig, ax = plt.subplots(figsize=(fig_width, fig_height))

        ax.set_title(f"{wagon_id} - {title_suffix}", fontsize=14)
        ax.set_xlim(0, wagon_length)
        ax.set_ylim(0, wagon_width)
        ax.set_xlabel("Length")
        ax.set_ylabel("Width")

        # Wagon boundary
        wagon_boundary = Rectangle(
            (0, 0),
            wagon_length,
            wagon_width,
            fill=False,
            linewidth=2.0,
        )
        ax.add_patch(wagon_boundary)

        # Centerline and front/rear line
        ax.axhline(
            wagon_width / 2,
            linestyle="--",
            linewidth=1,
        )
        ax.axvline(
            wagon_length / 2,
            linestyle="--",
            linewidth=1,
        )

        # Add centerline labels
        ax.text(
            wagon_length * 0.01,
            wagon_width / 2,
            "Centerline",
            fontsize=8,
            va="bottom",
        )
        ax.text(
            wagon_length / 2,
            wagon_width * 0.98,
            "Front/Rear split",
            fontsize=8,
            ha="center",
            va="top",
        )

        # Draw products
        for product in products:
            self.draw_product(ax, product)

        # Wagon summary text
        summary_text = self.build_wagon_summary_text(wagon)
        ax.text(
            1.01,
            0.98,
            summary_text,
            transform=ax.transAxes,
            fontsize=8,
            va="top",
            ha="left",
            bbox=dict(boxstyle="round", alpha=0.15),
        )

        ax.set_aspect("equal", adjustable="box")
        ax.grid(True, linewidth=0.3, alpha=0.4)

        plt.tight_layout()
        plt.savefig(output_path, dpi=self.figure_dpi, bbox_inches="tight")
        plt.close(fig)

    def draw_product(self, ax, product: Dict[str, Any]) -> None:
        x = self.safe_float(product.get("x"))
        y = self.safe_float(product.get("y"))
        placed_length = self.safe_float(product.get("placed_length", product.get("length")))
        placed_width = self.safe_float(product.get("placed_width", product.get("width")))

        product_id = str(product.get("product_id", ""))
        destination = str(product.get("destination", ""))
        weight = self.safe_float(product.get("weight", 0))
        rotated = product.get("rotated", False)

        rect = Rectangle(
            (x, y),
            placed_length,
            placed_width,
            alpha=0.35,
            linewidth=1.0,
            edgecolor="black",
        )
        ax.add_patch(rect)

        label = (
            f"{product_id}\n"
            f"{destination}\n"
            f"{weight / 1000:.1f}t"
        )

        if rotated:
            label += "\nR"

        font_size = self.get_label_font_size(placed_length, placed_width)

        ax.text(
            x + placed_length / 2,
            y + placed_width / 2,
            label,
            ha="center",
            va="center",
            fontsize=font_size,
        )

    def get_label_font_size(self, placed_length: float, placed_width: float) -> int:
        area = placed_length * placed_width

        if area < 600_000:
            return 5
        if area < 1_200_000:
            return 6
        if area < 2_000_000:
            return 7
        return 8

    # ============================================================
    # PDF report
    # ============================================================

    def generate_pdf_report(
        self,
        loading_solution: Dict[str, Any],
        wagons: List[Dict[str, Any]],
        pdf_path: str | Path,
    ) -> None:
        with PdfPages(pdf_path) as pdf:
            self.add_cover_page(pdf, loading_solution)

            for wagon in wagons:
                self.add_wagon_layout_page(pdf, wagon)

            self.add_summary_page(pdf, loading_solution)

    def add_cover_page(self, pdf: PdfPages, loading_solution: Dict[str, Any]) -> None:
        fig, ax = plt.subplots(figsize=(11.69, 8.27))
        ax.axis("off")

        metadata = loading_solution.get("solution_metadata", {})
        wagon_summary = loading_solution.get("wagon_summary", {})
        initial_score = loading_solution.get("initial_solution_score", {})
        final_score = loading_solution.get("final_solution_score", {})
        strategy_summary = loading_solution.get("llm_strategy_plan_summary", {})

        title = "Loading Visualisation Report"

        text = f"""
{title}

Generated by: VisualizationAgent

Strategy used:
{metadata.get("strategy_used", "N/A")}

Scenario type:
{strategy_summary.get("scenario_type", "N/A")}

Number of wagons:
{wagon_summary.get("wagon_count", "N/A")}

Total products:
{wagon_summary.get("total_products", "N/A")}

Total weight:
{self.safe_float(wagon_summary.get("total_weight", 0)) / 1000:.2f} tonnes

Average area utilisation:
{self.safe_float(wagon_summary.get("average_area_utilisation", 0)) * 100:.2f}%

Initial objective score:
{self.safe_float(initial_score.get("objective_score", 0)):.2f}

Final objective score:
{self.safe_float(final_score.get("objective_score", 0)):.2f}

Strategy reason:
{strategy_summary.get("strategy_reason", "N/A")}
""".strip()

        ax.text(
            0.05,
            0.95,
            text,
            va="top",
            ha="left",
            fontsize=12,
            wrap=True,
        )

        pdf.savefig(fig)
        plt.close(fig)

    def add_wagon_layout_page(self, pdf: PdfPages, wagon: Dict[str, Any]) -> None:
        wagon_id = wagon.get("wagon_id", "Unknown Wagon")
        wagon_length = self.safe_float(wagon.get("length", 12000))
        wagon_width = self.safe_float(wagon.get("width", 2500))
        products = wagon.get("products", [])

        fig_width = 13
        fig_height = max(4, fig_width * wagon_width / wagon_length)

        fig, ax = plt.subplots(figsize=(fig_width, fig_height))

        ax.set_title(f"{wagon_id} - Final Loading Layout", fontsize=14)
        ax.set_xlim(0, wagon_length)
        ax.set_ylim(0, wagon_width)
        ax.set_xlabel("Length")
        ax.set_ylabel("Width")

        wagon_boundary = Rectangle(
            (0, 0),
            wagon_length,
            wagon_width,
            fill=False,
            linewidth=2.0,
        )
        ax.add_patch(wagon_boundary)

        ax.axhline(wagon_width / 2, linestyle="--", linewidth=1)
        ax.axvline(wagon_length / 2, linestyle="--", linewidth=1)

        for product in products:
            self.draw_product(ax, product)

        summary_text = self.build_wagon_summary_text(wagon)

        ax.text(
            1.01,
            0.98,
            summary_text,
            transform=ax.transAxes,
            fontsize=8,
            va="top",
            ha="left",
            bbox=dict(boxstyle="round", alpha=0.15),
        )

        ax.set_aspect("equal", adjustable="box")
        ax.grid(True, linewidth=0.3, alpha=0.4)

        plt.tight_layout()
        pdf.savefig(fig, bbox_inches="tight")
        plt.close(fig)

    def add_summary_page(self, pdf: PdfPages, loading_solution: Dict[str, Any]) -> None:
        fig, ax = plt.subplots(figsize=(11.69, 8.27))
        ax.axis("off")

        wagon_summary = loading_solution.get("wagon_summary", {})
        final_score = loading_solution.get("final_solution_score", {})
        sa_log = loading_solution.get("simulated_annealing_log", {})
        strategy_summary = loading_solution.get("llm_strategy_plan_summary", {})

        required_constraints = strategy_summary.get("required_constraints", [])
        risk_notes = strategy_summary.get("risk_notes", [])

        text = f"""
Summary

Wagon summary:
{json.dumps(wagon_summary, ensure_ascii=False, indent=2)}

Final solution score:
{json.dumps(final_score, ensure_ascii=False, indent=2)}

Simulated annealing log:
{json.dumps(sa_log, ensure_ascii=False, indent=2)[:2500]}

Required constraints suggested by LLM Agent:
{json.dumps(required_constraints, ensure_ascii=False, indent=2)}

Risk notes suggested by LLM Agent:
{json.dumps(risk_notes, ensure_ascii=False, indent=2)}
""".strip()

        ax.text(
            0.05,
            0.95,
            text,
            va="top",
            ha="left",
            fontsize=8,
            family="monospace",
            wrap=True,
        )

        pdf.savefig(fig)
        plt.close(fig)

    # ============================================================
    # Summary
    # ============================================================

    def build_visualization_summary(
        self,
        loading_solution: Dict[str, Any],
        layout_image_paths: List[str],
        pdf_path: str,
    ) -> Dict[str, Any]:
        wagon_summary = loading_solution.get("wagon_summary", {})
        strategy_summary = loading_solution.get("llm_strategy_plan_summary", {})

        return {
            "generated_by": "VisualizationAgent",
            "input_file": str(self.loading_solution_path),
            "layout_images": layout_image_paths,
            "pdf_report": pdf_path,
            "summary_output_path": str(self.summary_output_path),
            "wagon_count": wagon_summary.get("wagon_count"),
            "total_products": wagon_summary.get("total_products"),
            "total_weight": wagon_summary.get("total_weight"),
            "average_area_utilisation": wagon_summary.get("average_area_utilisation"),
            "strategy_used": strategy_summary.get("selected_strategy"),
            "scenario_type": strategy_summary.get("scenario_type"),
        }

    def build_wagon_summary_text(self, wagon: Dict[str, Any]) -> str:
        balance = wagon.get("balance_metrics", {})

        text = f"""
Products: {len(wagon.get("products", []))}
Weight: {self.safe_float(wagon.get("current_weight", 0)) / 1000:.2f} t
Max weight: {self.safe_float(wagon.get("max_weight", 0)) / 1000:.2f} t
Utilisation: {self.safe_float(wagon.get("area_utilisation", 0)) * 100:.2f}%

Left: {self.safe_float(balance.get("left_weight", 0)) / 1000:.2f} t
Right: {self.safe_float(balance.get("right_weight", 0)) / 1000:.2f} t
Front: {self.safe_float(balance.get("front_weight", 0)) / 1000:.2f} t
Rear: {self.safe_float(balance.get("rear_weight", 0)) / 1000:.2f} t
D1: {self.safe_float(balance.get("diagonal_1_weight", 0)) / 1000:.2f} t
D2: {self.safe_float(balance.get("diagonal_2_weight", 0)) / 1000:.2f} t
""".strip()

        return text

    # ============================================================
    # Utilities
    # ============================================================

    def export_json(self, data: Dict[str, Any], output_path: str | Path) -> Path:
        output_path = Path(output_path)
        output_path.parent.mkdir(parents=True, exist_ok=True)

        with output_path.open("w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, indent=2)

        return output_path

    @staticmethod
    def safe_float(value: Any) -> float:
        try:
            if value is None:
                return 0.0
            if isinstance(value, str) and not value.strip():
                return 0.0
            return float(value)
        except Exception:
            return 0.0


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Visualization Agent for loading_solution.json."
    )

    parser.add_argument(
        "--solution",
        default="Agents/loading_solution.json",
        help="Path to loading_solution.json generated by OptimisationAgent.",
    )
    parser.add_argument(
        "--output-dir",
        default="demo_outputs",
        help="Directory for layout images and PDF report.",
    )
    parser.add_argument(
        "--summary",
        default="Agents/visualization_summary.json",
        help="Path to visualization_summary.json.",
    )
    parser.add_argument(
        "--dpi",
        type=int,
        default=200,
        help="DPI for generated layout images.",
    )

    args = parser.parse_args()

    agent = VisualizationAgent(
        loading_solution_path=args.solution,
        output_dir=args.output_dir,
        summary_output_path=args.summary,
        figure_dpi=args.dpi,
    )

    agent.run()


if __name__ == "__main__":
    main()
